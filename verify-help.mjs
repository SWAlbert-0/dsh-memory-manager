import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const CHROME = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const PORT = 9229;
const URL = process.argv[2];
const PROFILE = 'D:\\Documents\\Temp\\chrome-dsh-profile-help';
spawn(CHROME, ['--headless=new','--disable-gpu','--no-sandbox','--no-first-run','--remote-debugging-port='+PORT,'--remote-allow-origins=*','--user-data-dir='+PROFILE,'--window-size=1440,1000','about:blank'], { detached: true, stdio: 'ignore' }).unref();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
for (let i = 0; i < 60; i++) { try { const r = await fetch(`http://127.0.0.1:${PORT}/json/version`); if (r.ok) break; } catch {} await sleep(250); }
const tab = await (await fetch(`http://127.0.0.1:${PORT}/json/new?${encodeURIComponent(URL)}`, { method: 'PUT' })).json();
const ws = new WebSocket(tab.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.rej(new Error(JSON.stringify(m.error))) : p.res(m.result); } };
const send = (method, params = {}) => new Promise((res, rej) => { const i = ++id; pending.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method, params })); });
const ev = async (expression) => (await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })).result?.value;
await send('Page.enable'); await send('Runtime.enable');
await sleep(6000);
await ev(`(() => { const el = [...document.querySelectorAll('button,a,div')].find(e => e.innerText && e.innerText.trim() === '记忆'); if (el) el.click(); return !!el })()`);
await sleep(1000);
const tabs = await ev(`[...document.querySelectorAll('[role=tab]')].map(t => t.innerText)`);
console.log('tabs:', JSON.stringify(tabs));
const clicked = await ev(`(() => { const b = document.getElementById('dshmem-tab-help'); if (b) { b.click(); return true } return false })()`);
console.log('clicked help:', clicked);
await sleep(900);
const text = String(await ev(`document.querySelector('[role=tabpanel]').innerText`));
console.log('--- help panel ---');
console.log(text);
const overflow = await ev(`(() => { const p = document.querySelector('.dshmem-root'); return { scrollWidth: p.scrollWidth, clientWidth: p.clientWidth }; })()`);
console.log('overflow:', JSON.stringify(overflow));
const shot = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync('D:\\Dev\\Projects\\Personal\\dsh-plugin\\dsh-memory-manager\\help-light.png', Buffer.from(shot.data, 'base64'));
await ev(`document.body.setAttribute('data-ds-dark-theme',''); true`);
await sleep(500);
const shot2 = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync('D:\\Dev\\Projects\\Personal\\dsh-plugin\\dsh-memory-manager\\help-dark.png', Buffer.from(shot2.data, 'base64'));
await send('Browser.close').catch(() => {});
process.exit(0);
