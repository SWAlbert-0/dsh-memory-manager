const ws = new WebSocket(tab.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.rej(new Error(JSON.stringify(m.error))) : p.res(m.result); } };
const send = (method, params = {}) => new Promise((res, rej) => { const i = ++id; pending.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method, params })); });
const ev = async (expression) => (await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })).result?.value;
await send('Page.enable'); await send('Runtime.enable');
await sleep(5500);
await ev(`(() => { const b = document.querySelector('[aria-label="记忆"]'); if (b) b.click(); return !!b })()`);
await sleep(1200);
const firstText = () => ev(`document.querySelector('.dshmem-card')?.innerText.split('\\n')[0] || null`);
console.log('first (default updated):', await firstText());
await ev(`(() => { const s = document.querySelector('select[aria-label="排序方式"]'); const setter = Object.getOwnPropertyDescriptor(window.HTMLSelectElement.prototype, 'value').set; setter.call(s, 'importance'); s.dispatchEvent(new Event('change', { bubbles: true })); return true })()`);
await sleep(500);
console.log('first (importance):', await firstText());
console.log('count label:', await ev(`(() => { const s = [...document.querySelectorAll('.dshmem-root span')].find(x => /显示 \\d+ \\/ \\d+ 条/.test(x.innerText)); return s ? s.innerText : null })()`));
const light = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync('D:\\Documents\\Temp\\dsh-memory-plugin\\filters-light.png', Buffer.from(light.data, 'base64'));
await ev(`document.body.setAttribute('data-ds-dark-theme',''); true`);
await sleep(500);
const dark = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync('D:\\Documents\\Temp\\dsh-memory-plugin\\filters-dark.png', Buffer.from(dark.data, 'base64'));
